'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const source=fs.readFileSync(path.join(root,'assets/app.js'),'utf8');
assert.match(html,/El modelo activo es V3/);
assert.doesNotMatch(html,/V3 frente a V2|assets\/v3-lab\.js/);
assert.match(source,/metrics\.active_model/);
assert.match(source,/Pronósticos V3 evaluados/);
console.log('OK: V3 aparece como modelo activo y la página no muestra el laboratorio V2.');
